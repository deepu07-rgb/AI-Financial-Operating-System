import { useState } from "react";
import { CircleHelp, Trash2 } from "lucide-react";
import { deleteSampleWorkspace } from "./onboarding";
import { PilotPage } from "./PilotPage";
import type { WorkspaceSummary } from "./review";

function messageFrom(error: unknown): string {
  return error instanceof Error ? error.message : String(error);
}

export function DiagnosticsPage({
  workspace,
  onWorkspaceChange,
}: {
  workspace: WorkspaceSummary;
  onWorkspaceChange: () => Promise<void>;
}) {
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");

  const removeSample = async () => {
    if (
      !workspace.isSample ||
      !window.confirm(
        `Delete the synthetic sample workspace "${workspace.name}"? This removes only its generated sample data.`,
      )
    ) {
      return;
    }
    setBusy(true);
    setError("");
    try {
      await deleteSampleWorkspace(workspace.id);
      await onWorkspaceChange();
    } catch (caught) {
      setError(messageFrom(caught));
    } finally {
      setBusy(false);
    }
  };

  return (
    <div className="page-stack diagnostics-page">
      <section className="module-intro diagnostics-intro">
        <div>
          <p className="eyebrow">Help and diagnostics</p>
          <h2>Understand and support this workspace</h2>
          <p>
            Review local health evidence, onboarding progress, privacy-safe
            support information, and product boundaries.
          </p>
        </div>
        <CircleHelp aria-hidden="true" size={34} />
      </section>
      {workspace.isSample ? (
        <section className="sample-management-card">
          <div>
            <span className="sample-badge">Sample data</span>
            <h3>Northstar Components is safe to remove</h3>
            <p>
              This workspace was generated by AIFOS for exploration. Deleting it
              cannot select or remove a real company workspace.
            </p>
          </div>
          <button
            className="danger-button"
            disabled={busy}
            onClick={() => void removeSample()}
            type="button"
          >
            <Trash2 aria-hidden="true" size={17} />
            {busy ? "Deleting sample..." : "Delete sample workspace"}
          </button>
        </section>
      ) : null}
      {error ? (
        <p className="review-error" role="alert">
          {error}
        </p>
      ) : null}
      <PilotPage />
    </div>
  );
}
